"""金额容差策略（落桩：闭区间工程形态）。

工程形态裁决（二选一，本仓取闭区间）：
- 闭区间容差：|差额分| <= 容差分 → 对齐，不进悬账，不写旁路凭证，结论读对齐集；
- 开区间旁路凭证：|差额分| == 容差分 也算不符，写旁路凭证供页回读，结论读不符集。

选闭区间的依据：基线 happy path 即 `<= 容差`（默认容差 0，等值必须对齐），
开区间会翻转默认口径并为本仓语义里不存在的「旁路匣凭证」造表，违反对拍骨架。

边界可区分性：贴边（|差|==容差）与纯内（|差|<容差）虽然差型同为「对齐」，
裁决结果带「贴边」标记；旁路凭证字段闭区间恒为 None，与开区间形态的有凭证显式不同。
"""
from __future__ import annotations

NAME = "金额容差策略"
形态 = "闭区间"


def 裁决(业务键: str, 左金额分: int, 右金额分: int, 容差分: int) -> dict:
    """纯函数：双边同键金额差的容差裁决，不落库。"""
    if 左金额分 is None or 右金额分 is None:
        raise ValueError("容差裁决仅处理双边同键金额，缺边差型由对齐服务另判")
    左 = int(左金额分)
    右 = int(右金额分)
    容差 = int(容差分)
    if 容差 < 0:
        raise ValueError("容差分不可为负")
    差额 = abs(左 - 右)
    贴边 = 差额 == 容差
    对齐 = 差额 <= 容差  # 闭区间：等值贴边也算对齐
    return {
        "业务键": 业务键,
        "左金额分": 左,
        "右金额分": 右,
        "容差分": 容差,
        "差额分": 差额,
        "差型": "对齐" if 对齐 else "金额不符",
        "贴边": 贴边,
        "valid": 对齐,
        # 闭区间形态不产生旁路凭证；开区间形态此处会是凭证对象，二者读引用不同
        "旁路凭证": None,
        "形态": 形态,
    }


def 只读接口(业务键: str, 左金额分: int, 右金额分: int, 容差分: int | None = None) -> dict:
    """只读裁决接口：容差分缺省时读轨规当前值，全程不写库。"""
    if 容差分 is None:
        from app.services import 目录
        容差分 = int(目录.轨规().get("金额容差分", "0"))
    return 裁决(业务键, 左金额分, 右金额分, 容差分)
